"""Derive the phase 2b resource files from the phase 1 files under ``managed/``.

A self-hosted Managed Agents server exposes the same API, so most files carry over
unchanged. This script applies the few changes the server requires and prints each one.
The printed list *is* the migration: read it next to Guide 21.

    uv run python phase2/b-self-hosted-service/make_managed.py

The output (``phase2/b-self-hosted-service/managed/``) is committed so it can be read
without running anything. A test keeps it in sync with ``managed/``.
"""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE = REPO_ROOT / "managed"
TARGET = Path(__file__).resolve().parent / "managed"

HEADER = (
    "# GENERATED by phase2/b-self-hosted-service/make_managed.py from managed/{path}.\n"
    "# Do not edit: change the source file or the script, then run the script again.\n"
)


def split_agent_file(text: str) -> tuple[dict[str, Any], str]:
    _, frontmatter, body = text.split("---\n", 2)
    return yaml.safe_load(frontmatter), body


def transform_agent(name: str, config: dict[str, Any], body: str) -> tuple[str, list[str]]:
    """Apply the self-hosted differences to one agent. Returns (body, list of changes)."""
    changes: list[str] = []

    multiagent = config.get("multiagent")
    if multiagent:
        # Only the older `coordinator` type is accepted: a fixed list of 1 to 20 agents.
        # No advisor, no dynamic workflows, no agents the coordinator defines itself.
        roster = multiagent["subagents"]["predefined_agents"]
        config["multiagent"] = {"type": "coordinator", "agents": roster}
        changes.append("multiagent: multiagent_20261001 -> coordinator (fixed roster only)")
        if multiagent.get("advisor", {}).get("type") == "enabled":
            changes.append(f"advisor ({multiagent['advisor']['model']}): removed, not available")
        if multiagent.get("workflows", {}).get("type") == "enabled":
            changes.append("dynamic workflows: removed, not available")

        # The prompt must not promise what the server cannot do.
        body = body.replace(
            "- When there are more than three proposals to review, start a workflow run that "
            "gives each\n  proposal to its own cfp-reviewer in parallel, then collects the "
            "results. Review one to three\n  proposals by delegating to a single cfp-reviewer, "
            "without a run.\n- In a run, one reviewer failing must not fail the run. List a "
            'proposal whose reviewer failed\n  as "Not covered".\n',
            "- Delegate the proposals to cfp-reviewers, a few proposals per reviewer. If a "
            'reviewer fails,\n  list its proposals as "Not covered".\n',
        )
        body = body.replace(
            "- Before you ask the scheduler to book, consult your advisor about the proposed "
            "acceptances\n  and a running order: variety of topics and tracks, a mix of "
            "first-time and returning\n  speakers, and a sensible order for the evening. Then "
            "accept the proposals and give the\n  scheduler the running order as a suggestion.\n",
            "- Before you ask the scheduler to book, check the proposed acceptances and a "
            "running order\n  yourself: variety of topics and tracks, a mix of first-time and "
            "returning speakers, and a\n  sensible order for the evening. Then accept the "
            "proposals and give the scheduler the\n  running order as a suggestion.\n",
        )
        changes.append("system prompt: workflow and advisor instructions rewritten")
        if "workflow run" in body or "advisor" in body:
            raise SystemExit(f"{name}: the prompt still mentions workflows or the advisor.")

        # The sponsor-perk step uses the host-tool variant (see below).
        config["multiagent"]["agents"] = [
            entry.replace("../speaker-liaison/", "../speaker-liaison-host-tool/")
            for entry in config["multiagent"]["agents"]
        ]
        body = body.replace("speaker-liaison", "speaker-liaison-host-tool")
        changes.append("roster: speaker-liaison -> speaker-liaison-host-tool")

    return body, changes


def generate(target_dir: Path) -> list[str]:
    """Write the phase 2b files into ``target_dir`` and return the list of changes.

    # Guide 21 · Migrating to self-hosted Managed Agents · Step 1: derive the resource files
    """
    if target_dir.exists():
        shutil.rmtree(target_dir)
    report: list[str] = []

    for source in sorted(SOURCE.rglob("*")):
        if not source.is_file() or source.name == "claude-lock.json":
            continue
        relative = source.relative_to(SOURCE)
        top = relative.parts[0]

        if top == "deployments":
            report.append(f"SKIP  {relative}: no scheduled deployments. Use cron (see cron/).")
            continue
        if top == "environments":
            report.append(
                f"SKIP  {relative}: the server creates its own self_hosted environment. "
                "Set CONCIERGE_ENVIRONMENT_ID to its ID."
            )
            continue
        if relative.parts[:2] == ("agents", "speaker-liaison"):
            report.append(
                f"SKIP  {relative}: environment_variable vault credentials are rejected "
                "unless the egress gateway is enabled. speaker-liaison-host-tool replaces it."
            )
            continue

        target = target_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        header = HEADER.format(path=relative.as_posix())

        if source.name == "agent.md":
            config, body = split_agent_file(source.read_text(encoding="utf-8"))
            body, changes = transform_agent(config["name"], config, body)
            frontmatter = yaml.safe_dump(config, sort_keys=False, width=100)
            target.write_text(f"---\n{header}{frontmatter}---\n{body}", encoding="utf-8")
            status = "EDIT " if changes else "COPY "
            report.append(f"{status} {relative}")
            report.extend(f"        - {change}" for change in changes)
        else:
            target.write_text(header + source.read_text(encoding="utf-8"), encoding="utf-8")
            report.append(f"COPY  {relative}")

    return report


def main() -> None:
    print("\n".join(generate(TARGET)))


if __name__ == "__main__":
    main()
